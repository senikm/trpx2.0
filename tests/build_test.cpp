// The values that were compressed into the v1 files above.
template <typename T>
T v1_value(std::size_t frame, std::size_t i) {
    if ((i / 8) % 3 == 1) return 0;
    if constexpr (std::is_signed_v<T>)
        return i == 17 ? T(100000) : i % 7 == 0 ? T(-1) : T(static_cast<int>((i * 53 + frame * 17) % 2001) - 1000);
    else
        return frame == 1 ? T(i % 5) : T((i * 37 + frame * 101) % 3000);
}

template <typename T, typename CONCURRENT, std::size_t N>
bool read_v1(char const* name, unsigned char const (&file)[N], std::size_t frames) {
    std::istringstream stream(std::string(reinterpret_cast<char const*>(file), N));
    jpa::Terse<CONCURRENT> read(stream);
    bool ok = read.number_of_frames() == frames && read.size() == 45;
    for (std::size_t frame = 0; ok && frame < frames; ++frame) {
        std::vector<T> result(read.size());
        read.prolix(result.begin(), frame);
        for (std::size_t i = 0; i < result.size(); ++i)
            ok &= result[i] == v1_value<T>(frame, i);
    }
    std::printf("%-8s %-14s %-10s %s\n", name, "v1 file", std::is_same_v<CONCURRENT, void> ? "void" : "Concurrent",
                ok ? "ok" : "FAILED");
    return ok;
}

template <typename CONCURRENT>
bool read_v1_files() {
    bool ok = read_v1<std::uint16_t, CONCURRENT>("uint16", v1_uint16, 3);
    ok &= read_v1<std::int32_t, CONCURRENT>("int32", v1_int32, 2);
    return ok;
}

int main() {
    bool const single_threaded = round_trips<void>();
    bool const concurrent = round_trips<jpa::Concurrent>();
    bool const v1 = read_v1_files<void>() && read_v1_files<jpa::Concurrent>();
    return single_threaded && concurrent && v1 ? 0 : 1;
}
